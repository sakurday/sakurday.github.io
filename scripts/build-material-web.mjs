import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { build } from "esbuild";

const outputDirectory = "assets/vendor";
const result = await build({
  stdin: {
    contents: [
      'import "@material/web/button/filled-button.js";',
      'import "@material/web/button/filled-tonal-button.js";',
      'import "@material/web/button/text-button.js";',
      'import "@material/web/divider/divider.js";',
      'import "@material/web/focus/md-focus-ring.js";',
      'import "@material/web/iconbutton/filled-tonal-icon-button.js";',
      'import "@material/web/ripple/ripple.js";',
    ].join("\n"),
    resolveDir: process.cwd(),
  },
  bundle: true,
  format: "esm",
  minify: true,
  metafile: true,
  write: false,
  banner: { js: "// Generated by npm run build:material. See material-web.LICENSE.txt." },
});

const packageDirectories = new Set();
for (const input of Object.keys(result.metafile.inputs)) {
  const match = input.match(/^(.*\bnode_modules\/(?:@[^/]+\/)?[^/]+)\//);
  if (match) packageDirectories.add(match[1]);
}

const notices = await Promise.all([...packageDirectories].sort().map(async (directory) => {
  const { name, version } = JSON.parse(await readFile(join(directory, "package.json"), "utf8"));
  const files = await readdir(directory);
  const license = files.find((file) => /^licen[cs]e(?:\.(?:txt|md))?$/i.test(file));
  if (!license) throw new Error(`License missing for ${name}@${version}`);
  const notice = files.find((file) => /^notice(?:\.(?:txt|md))?$/i.test(file));
  const documents = await Promise.all([license, notice].filter(Boolean).map(
    (file) => readFile(join(directory, file), "utf8"),
  ));
  return [`${name}@${version}`, ...documents.map((document) => document.trim())].join("\n\n");
}));

await mkdir(outputDirectory, { recursive: true });
await writeFile(join(outputDirectory, "material-web.LICENSE.txt"), notices.join("\n\n---\n\n") + "\n");
await writeFile(join(outputDirectory, "material-web.js"), result.outputFiles[0].contents);
